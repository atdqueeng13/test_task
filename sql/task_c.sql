-- Задание в)
-- Вывести id клиентов, сделавших больше 5 заказов
-- в ресторанах "Теремок" и "Вкусно и точка"
-- на сумму от 2000 до 10000 рублей.
-- Также вернуть сумму их самого дорогого заказа для этого фильтра.
-- Столбцы назвать "frequent_customer" и "max_sum".
--
-- "На сумму от 2 до 10 тысяч" понимаю как сумму каждого заказа,
-- поэтому фильтрую в WHERE, до группировки. Заказы считаются
-- по обоим ресторанам вместе.

SELECT
    order_client_id AS frequent_customer,
    MAX(price) AS max_sum
FROM orders
WHERE place IN ('Теремок', 'Вкусно и точка')
  AND price BETWEEN 2000 AND 10000
GROUP BY order_client_id
HAVING COUNT(*) > 5;
